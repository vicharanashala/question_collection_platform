import { EmailOtpPurpose } from "../../../shared/classes/enums";

/** Content-ID of the Annam logo that EmailService attaches to HTML emails. */
export const EMAIL_LOGO_CID = "annam-logo";

export interface OtpEmail {
  subject: string;
  text: string;
  html: string;
}

const FONT_STACK =
  "-apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, Helvetica, Arial, sans-serif";
const CODE_FONT_STACK =
  "'SFMono-Regular', Menlo, Consolas, 'Courier New', monospace";

const COPY: Record<
  EmailOtpPurpose,
  { subject: string; heading: string; intro: string }
> = {
  [EmailOtpPurpose.EMAIL_SYNC]: {
    subject: "Your AnnaDatha verification code",
    heading: "Verify your email address",
    intro:
      "Use this code to link this email address to your AnnaDatha account.",
  },
  [EmailOtpPurpose.EMAIL_LOGIN]: {
    subject: "Your AnnaDatha sign-in code",
    heading: "Your sign-in code",
    intro: "Use this code to sign in to your AnnaDatha account.",
  },
};

/**
 * Builds the subject, plain-text and HTML versions of an OTP email. The HTML uses
 * tables and inline styles so it renders the same in Gmail, Outlook and phone apps.
 * The OTP is generated by the server and contains only digits, so it needs no escaping.
 */
export function buildOtpEmail(
  otp: string,
  purpose: EmailOtpPurpose,
  expiryMinutes: number,
): OtpEmail {
  const { subject, heading, intro } = COPY[purpose];
  const year = new Date().getFullYear();

  const text = [
    heading,
    "",
    intro,
    "",
    `Your code: ${otp}`,
    `This code expires in ${expiryMinutes} minutes.`,
    "",
    "Keep this code private. AnnaDatha will never ask you for it by phone, SMS or email.",
    "If you did not request this code, you can safely ignore this email.",
    "",
    `AnnaDatha by Annam.ai`,
  ].join("\n");

  const html = `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="color-scheme" content="light">
<meta name="supported-color-schemes" content="light">
<title>${subject}</title>
</head>
<body style="margin:0;padding:0;background-color:#f3f6f4;">
<div style="display:none;max-height:0;overflow:hidden;opacity:0;mso-hide:all;">${heading}: ${otp}. It expires in ${expiryMinutes} minutes.</div>
<table role="presentation" width="100%" cellpadding="0" cellspacing="0" border="0" style="background-color:#f3f6f4;">
  <tr>
    <td align="center" style="padding:32px 16px;">
      <table role="presentation" width="100%" cellpadding="0" cellspacing="0" border="0" style="max-width:520px;">
        <tr>
          <td align="center" style="padding-bottom:20px;">
            <table role="presentation" cellpadding="0" cellspacing="0" border="0">
              <tr>
                <td style="vertical-align:middle;padding-right:10px;">
                  <img src="cid:${EMAIL_LOGO_CID}" width="40" height="40" alt="Annam.ai" style="display:block;border:0;outline:none;">
                </td>
                <td style="vertical-align:middle;font-family:${FONT_STACK};font-size:20px;font-weight:700;color:#14532d;">AnnaDatha</td>
              </tr>
            </table>
          </td>
        </tr>
        <tr>
          <td style="background-color:#ffffff;border:1px solid #e3e8e5;border-top:4px solid #22a55a;border-radius:12px;">
            <table role="presentation" width="100%" cellpadding="0" cellspacing="0" border="0">
              <tr>
                <td style="padding:32px 32px 28px;font-family:${FONT_STACK};">
                  <h1 style="margin:0 0 8px;font-size:22px;line-height:30px;font-weight:700;color:#111827;">${heading}</h1>
                  <p style="margin:0 0 24px;font-size:15px;line-height:24px;color:#4b5563;">${intro}</p>
                  <table role="presentation" width="100%" cellpadding="0" cellspacing="0" border="0">
                    <tr>
                      <td align="center" style="background-color:#f0faf4;border:1px dashed #86d1a3;border-radius:10px;padding:18px 12px 18px 22px;font-family:${CODE_FONT_STACK};font-size:32px;line-height:40px;font-weight:700;letter-spacing:10px;color:#14532d;">${otp}</td>
                    </tr>
                  </table>
                  <p style="margin:16px 0 0;font-size:13px;line-height:20px;color:#6b7280;text-align:center;">This code expires in <strong style="color:#374151;">${expiryMinutes} minutes</strong>.</p>
                  <table role="presentation" width="100%" cellpadding="0" cellspacing="0" border="0" style="margin-top:28px;">
                    <tr><td style="border-top:1px solid #eef1ef;font-size:0;line-height:0;">&nbsp;</td></tr>
                  </table>
                  <p style="margin:20px 0 0;font-size:13px;line-height:20px;color:#6b7280;"><strong style="color:#374151;">Keep this code private.</strong> AnnaDatha will never ask you for it by phone, SMS or email. If you did not request this code, you can safely ignore this email.</p>
                </td>
              </tr>
            </table>
          </td>
        </tr>
        <tr>
          <td align="center" style="padding:20px 16px 0;font-family:${FONT_STACK};font-size:12px;line-height:18px;color:#9ca3af;">
            This is an automated message from AnnaDatha by Annam.ai. Please do not reply.<br>&copy; ${year} Annam.ai
          </td>
        </tr>
      </table>
    </td>
  </tr>
</table>
</body>
</html>`;

  return { subject, text, html };
}
